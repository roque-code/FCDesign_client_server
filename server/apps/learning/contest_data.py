def build_contest() -> dict[str, Any]:
    """Arma las unidades. Falla si una solución no corre en el laboratorio."""
    units = []
    total = 0
    for index, (concept, title, specs) in enumerate(_UNITS, start=1):
        challenges = [_materialize(spec, position) for position, spec in enumerate(specs, start=1)]
        total += len(challenges)
        units.append(
            {
                "title": title,
                "concept": concept,
                "position": 100 + index,
                "challenges": challenges,
            }
        )
    titles = [item["title"] for unit in units for item in unit["challenges"]]
    if total != 50 or len(titles) != len(set(titles)):
        raise ValueError(f"La práctica de concurso tiene {total} retos.")
    return {
        "name": CONTEST_BANK_NAME,
        "description": CONTEST_BANK_DESCRIPTION,
        "units": units,
    }


def _materialize(spec: dict[str, Any], position: int) -> dict[str, Any]:
    difficulty = spec["difficulty"]
    source = programa(spec["header"], spec["lines"]) if spec["header"] else algo(spec["lines"])
    if len(spec["samples"]) != 3:
        raise ValueError(f"{spec['title']}: hacen falta 3 casos.")
    cases = []
    for index, inputs in enumerate(spec["samples"]):
        output, _workspace, _printed = _prove(source, list(inputs), spec["title"])
        cases.append(
            {
                "name": _CASE_NAMES[index],
                "inputs": list(inputs),
                "expected_output": output,
                "kind": _CASE_KINDS[index],
                "position": index + 1,
            }
        )
    challenge: dict[str, Any] = {
        "title": spec["title"],
        "prompt": (
            spec["prompt"]
            + " Cada Leer muestra el dato en su propia línea; la salida esperada incluye esas líneas."
        ),
        "activity_type": "build",
        "difficulty": difficulty,
        "points": _POINTS[difficulty],
        "position": position,
        "allowed_blocks": [],
        "time_limit_seconds": _LIMIT[difficulty],
        "restrictions": {
            "question": spec["question"],
            "accepted": list(spec["accepted"]),
            "tools": list(_TOOLS),
        },
        "cases": cases,
        "hints": [
            {"level": 1, "position": 1, "body": spec["hint"]},
            {"level": 2, "position": 1, "body": _SECOND},
            {"level": 5, "position": 1, "body": _marked(spec["solve"])},
        ],
    }
    if len(challenge["title"]) > 120 or len(challenge["prompt"]) > 4000:
        raise ValueError(f"{spec['title']}: texto demasiado largo.")
    for hint in challenge["hints"]:
        if len(hint["body"]) > 500:
            raise ValueError(f"{spec['title']}: pista demasiado larga.")
    return challenge


def _marked(solve: str) -> str:
    body = f"{_SOLUTION}: {solve}"
    if len(body) > 500:
        return body[:497] + "..."
    return body


