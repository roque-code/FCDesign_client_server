const TABLES = {
  python: PYTHON_KEYWORDS,
  javascript: JAVASCRIPT_KEYWORDS,
  typescript: TYPESCRIPT_KEYWORDS,
  java: JAVA_KEYWORDS,
  c: C_KEYWORDS,
  cpp: CPP_KEYWORDS,
  csharp: CSHARP_KEYWORDS,
} as const

export function keywordsFor(language: ForeignLanguage): readonly string[] {
  return TABLES[language]
}

export function hashComment(language: ForeignLanguage): boolean {
  return language === "python" || language === "c" || language === "cpp"
}
